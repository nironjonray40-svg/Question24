def import_questions():
    with app.app_context():
        class_obj = ClassLevel.query.filter(ClassLevel.name.like('%৯ম-১০ম%')).first()
        if not class_obj:
            print("Class not found!")
            return
            
        subject_obj = Subject.query.filter_by(class_id=class_obj.id, name="বাংলা সাহিত্য").first()
        if not subject_obj:
            print("Subject not found!")
            return
            
        chapter_obj = Chapter.query.filter(
            Chapter.subject_id == subject_obj.id,
            Chapter.title.like('%অভাগীর স্বর্গ%')
        ).first()
        if not chapter_obj:
            print("Chapter not found!")
            return
            
        print(f"Target -> Class: {class_obj.name} (ID {class_obj.id}), Subject: {subject_obj.name} (ID {subject_obj.id}), Chapter: {chapter_obj.title} (ID {chapter_obj.id})")
        
        # Select appropriate topic (পাঠ ৭: পাঠ্যবইভিত্তিক বহুনির্বাচনি (MCQ) ও মূল্যায়ন)
        topic = None
        for t in chapter_obj.topics:
            if "MCQ" in t.title or "মূল্যায়ন" in t.title:
                topic = t
                break
        if not topic and chapter_obj.topics:
            topic = chapter_obj.topics[0]
            
        topic_id = topic.id if topic else None
        print(f"Assigned Topic: {topic.title if topic else 'None'} (ID {topic_id})")
        
        print(f"Total questions to insert: {len(questions_data)}")
        count = 0
        for item in questions_data:
            q = Question(
                class_id=class_obj.id,
                subject_id=subject_obj.id,
                chapter_id=chapter_obj.id,
                topic_id=topic_id,
                question_type='mcq',
                difficulty='medium',
                marks=1.0,
                mcq_stem=item['stem'],
                option_a=item['option_a'],
                option_b=item['option_b'],
                option_c=item['option_c'],
                option_d=item['option_d'],
                correct_option=item['correct_option'],
                explanation=item['explanation'] if item.get('explanation') else None
            )
            db.session.add(q)
            count += 1
            
        db.session.commit()
        print(f"Successfully inserted {count} MCQ questions into '{chapter_obj.title}'!")

if __name__ == '__main__':
    import_questions()
